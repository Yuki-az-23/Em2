#!/usr/bin/env python3
"""Self-updating project coordinator for EM2 (adapted from the architecture seed).

Builds a canonical project plan from the working tree, detects missing gates,
and can repair missing seed metadata without editing the seed files by hand.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Dict

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from scripts import seed_spec as spec

ROOT = Path(__file__).resolve().parents[1]

REQUIRED_FILES = spec.REQUIRED_FILES
REQUIRED_SKILLS = spec.REQUIRED_SKILLS
REQUIRED_MILESTONES = spec.MILESTONES
REQUIRED_WORKFLOWS = spec.WORKFLOWS
REQUIRED_VALIDATORS = spec.VALIDATORS


class SelfUpdatePlanner:
    def __init__(self, root: Path | str | None = None):
        self.root = Path(root) if root is not None else ROOT

    def build_plan(self) -> Dict[str, object]:
        missing = [rel for rel in REQUIRED_FILES if not (self.root / rel).exists()]
        legacy = [rel for rel in spec.LEGACY_PATHS if (self.root / rel).exists()]
        skills = [
            {
                "name": name,
                "path": f".claude/skills/{name}/SKILL.md",
                "present": (self.root / ".claude/skills" / name / "SKILL.md").exists(),
            }
            for name in REQUIRED_SKILLS
        ]
        if missing:
            status = "repair-needed"
        elif legacy:
            status = "fail"  # removed in M0; must not come back, and is never auto-repaired
        else:
            status = "pass"
        return {
            "project": spec.PROJECT,
            "status": status,
            "missing": missing,
            "legacy_present": legacy,
            "required_files": REQUIRED_FILES,
            "skills": skills,
            "milestones": REQUIRED_MILESTONES,
            "workflows": REQUIRED_WORKFLOWS,
            "validators": REQUIRED_VALIDATORS,
            "agent_registry": spec.AGENT_REGISTRY,
            "notes": [
                "manifest is canonical source for project state",
                "validator is mandatory before milestone signoff",
                "orchestrator must route work to the specific subsystem owner",
                "skills are the deploy and release boundary for Forgejo and Argo",
            ],
        }

    def sync_manifest(self) -> Dict[str, object]:
        # The manifest format is owned by project_manifest.py; delegate to it.
        from scripts.project_manifest import build_manifest

        manifest = build_manifest(self.root)
        (self.root / ".project-manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
        return manifest

    def sync_missing_files(self) -> Dict[str, object]:
        updated = []
        for rel in REQUIRED_FILES:
            path = self.root / rel
            if path.exists():
                continue
            path.parent.mkdir(parents=True, exist_ok=True)
            if rel.endswith("SKILL.md"):
                path.write_text(
                    "---\nname: placeholder\ndescription: generated placeholder\n---\n\n# Placeholder\n",
                    encoding="utf-8",
                )
            elif rel.endswith(".md"):
                path.write_text("# Placeholder\n\nGenerated by the recursive project coordinator.\n", encoding="utf-8")
            else:
                path.write_text("# generated\n", encoding="utf-8")
            updated.append(rel)

        result = self.build_plan()
        result["updated"] = updated
        if updated or not (self.root / ".project-manifest.json").exists():
            self.sync_manifest()
        return result


def main() -> None:
    parser = argparse.ArgumentParser(description="Self-update the project manifest and route work to the right gates.")
    parser.add_argument("--repair", action="store_true", help="Create any missing files and refresh the manifest.")
    args = parser.parse_args()

    planner = SelfUpdatePlanner(ROOT)
    if args.repair:
        report = planner.sync_missing_files()
    else:
        report = planner.build_plan()
        if report["missing"]:
            report = planner.sync_missing_files()
    print(json.dumps(report, indent=2))


if __name__ == "__main__":
    main()
